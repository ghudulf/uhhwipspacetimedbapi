"""Generate explicit SDK event subscriptions; rerun after spacetime generate (2.1.0)."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1] / 'BRU-AVTOPARK-AspireAPI/TicketSalesApp.Services'
lines = []
for path in sorted((root / 'client/module_bindings/Reducers').glob('*.g.cs')):
    match = re.search(r'public delegate void (\w+)Handler\((.*?)\);', path.read_text())
    if match:
        name, parameters = match.groups()
        names = [parameter.strip().split()[-1] for parameter in parameters.split(',')]
        lines.append(f'        connection.Reducers.On{name} += ({", ".join(names)}) => OnReducerCompleted(ctx);')
(root / 'Implementations/SpacetimeDBService.ReducerObservers.cs').write_text(
    '// Generated by tools/generate-reducer-observers.py; explicit callbacks for pinned SDK 2.1.0.\n'
    'using SpacetimeDB.Types;\nnamespace TicketSalesApp.Services.Implementations;\n'
    'public partial class SpacetimeDBService\n{\n    private void ObserveReducerCompletions(DbConnection connection)\n    {\n'
    + '\n'.join(lines) + '\n    }\n}\n')
