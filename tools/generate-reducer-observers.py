"""Generate explicit SDK event subscriptions; rerun after spacetime generate (2.1.0)."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1] / 'BRU-AVTOPARK-AspireAPI/TicketSalesApp.Services'
lines = []
for path in sorted((root / 'client/module_bindings/Reducers').glob('*.g.cs')):
    match = re.search(r'public delegate void (\w+)Handler\((.*?)\);', path.read_text())
    if match:
        name, parameters = match.groups()
        names = [parameter.strip().split()[-1] for parameter in parameters.split(',')]
        lines.extend([
            f'        RemoteReducers.{name}Handler on{name} = ({", ".join(names)}) => OnReducerCompleted(ctx);',
            f'        connection.Reducers.On{name} += on{name};',
            f'        _connectionUnsubscriptions.Add(() => connection.Reducers.On{name} -= on{name});'])
(root / 'Implementations/SpacetimeDBService.ReducerObservers.cs').write_text(
    '// Generated by tools/generate-reducer-observers.py; explicit callbacks for pinned SDK 2.1.0.\n'
    'using SpacetimeDB.Types;\nnamespace TicketSalesApp.Services.Implementations;\n'
    'public partial class SpacetimeDBService\n{\n    private void ObserveReducerCompletions(DbConnection connection)\n    {\n'
    + '\n'.join(lines) + '\n    }\n}\n')

changes = []
resources = {
    'Bus': 'Changes.Publish("buses")', 'BusRevision': 'Changes.Publish("buses")',
    'Route': 'Changes.Publish("routes")', 'Maintenance': 'Changes.Publish("maintenance")',
    'Employee': 'Changes.Publish("employees")', 'Job': 'Changes.Publish("jobs")',
    'RouteSchedule': 'Changes.Publish("schedules")', 'Ticket': 'Changes.Publish("tickets")',
    'Sale': 'Changes.Publish("sales")', 'SaleRevision': 'Changes.Publish("sales")',
    'UserProfile': 'PublishAccessChange("users")', 'UserRole': 'PublishAccessChange("users", "roles")',
    'Role': 'PublishAccessChange("roles")', 'Permission': 'PublishAccessChange("permissions")',
    'RolePermission': 'PublishAccessChange("roles", "permissions")',
    'EntityRevision': 'Changes.Publish(row.Key.Split(\':\')[0])',
}
for table, expression in resources.items():
    for event in ['Insert', 'Update', 'Delete']:
        args = f'EventContext context, {table} previous, {table} row' if event == 'Update' else f'EventContext context, {table} row'
        name = f'On{table}{event}'
        changes.extend([
            f'        void {name}({args}) => {expression};',
            f'        connection.Db.{table}.On{event} += {name};',
            f'        _connectionUnsubscriptions.Add(() => connection.Db.{table}.On{event} -= {name});'])
(root / 'Implementations/SpacetimeDBService.Changes.cs').write_text(
    '// Generated by tools/generate-reducer-observers.py; connection-owned, explicitly detached observers.\n'
    'using SpacetimeDB.Types;\nusing TicketSalesApp.Services.Interfaces;\nnamespace TicketSalesApp.Services.Implementations;\n'
    'public partial class SpacetimeDBService\n{\n    public DatabaseChangeJournal Changes { get; } = new();\n'
    '    private void ObserveApplicationChanges(DbConnection connection)\n    {\n        Changes.Reset();\n'
    + '\n'.join(changes) + '\n    }\n    private void PublishAccessChange(params string[] resources)\n    {\n'
    '        Changes.Publish("access");\n        foreach (var resource in resources) Changes.Publish(resource);\n    }\n}\n')
